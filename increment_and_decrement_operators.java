public class increment_and_decrement_operators {
    public static void main(String[] args) {
        
        //increment and decrement operrators

        //assigned variable values for x and y
        int x=1;
        int y=2;

        //incrementing x
        x=x+1;
        //x+=1
        //x++

        //incrementing y
        y=y-2;
        //y-=2
        //y--


        //prints output
        System.out.println("\nIncremented value: "+x);
        System.out.println("Decremented value: "+y);
    }
    
}
